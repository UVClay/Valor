#!/usr/bin/env python3
"""Writes engine/core/src/sintab.inc: PsyQ's rcossin_tbl sines (exe 0x8003040C), which equal
round(4096 sin) for all 4096 angles (tools/sim/move_sim.py); cos(a) = sin(a + 1024)."""
import math
import os

out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "core", "src", "sintab.inc")
vals = [round(4096 * math.sin(2 * math.pi * i / 4096)) for i in range(4096)]
with open(out, "w") as f:
    f.write("// Generated by engine/tools/gen_sintab.py: round(4096 sin(2 pi i / 4096)), i = 0..4095.\n")
    for i in range(0, 4096, 16):
        f.write(", ".join(str(v) for v in vals[i:i + 16]) + ",\n")
